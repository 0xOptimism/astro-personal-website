import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const postsDir = fileURLToPath(new URL('../src/content/posts', import.meta.url));
const outputUrl = new URL('../src/lib/writing.generated.ts', import.meta.url);

function unquote(value) {
  const trimmed = value.trim();
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

function parseFrontmatter(block) {
  const data = { tags: [], draft: false };
  let currentKey = '';

  for (const line of block.split(/\r?\n/)) {
    const nested = line.match(/^\s+-\s+(.+)$/);
    if (nested && currentKey === 'tags') {
      data.tags.push(unquote(nested[1]));
      continue;
    }

    const pair = line.match(/^([A-Za-z][A-Za-z0-9]*)\s*:\s*(.*)$/);
    if (!pair) continue;

    currentKey = pair[1] ?? '';
    const raw = pair[2] ?? '';

    if (currentKey === 'tags') {
      data.tags = [];
      continue;
    }
    if (currentKey === 'draft') {
      data.draft = unquote(raw) === 'true';
      continue;
    }
    if (
      currentKey === 'title' ||
      currentKey === 'description' ||
      currentKey === 'pubDate' ||
      currentKey === 'updatedDate' ||
      currentKey === 'xPostUrl'
    ) {
      data[currentKey] = unquote(raw);
    }
  }

  return data;
}

async function listPostFiles(dir, relative = '') {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const name = relative ? `${relative}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...(await listPostFiles(join(dir, entry.name), name)));
      continue;
    }
    if (entry.isFile() && entry.name.endsWith('.md')) {
      files.push(name);
    }
  }

  return files.sort();
}

function parsePost(source, relativePath) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) {
    throw new Error(`Missing frontmatter in ${relativePath}`);
  }

  const data = parseFrontmatter(match[1] ?? '');
  if (!data.title || !data.description || !data.pubDate) {
    throw new Error(`Post ${relativePath} needs title, description, and pubDate`);
  }

  const record = {
    id: relativePath.replace(/\\/g, '/').replace(/\.md$/i, ''),
    title: data.title,
    description: data.description,
    pubDate: data.pubDate,
    tags: data.tags,
    draft: data.draft,
    body: (match[2] ?? '').trim(),
  };

  if (data.updatedDate) {
    record.updatedDate = data.updatedDate;
  }
  if (data.xPostUrl) {
    record.xPostUrl = data.xPostUrl;
  }

  return record;
}

const filenames = await listPostFiles(postsDir);
const posts = await Promise.all(
  filenames.map(async (filename) => {
    const source = await readFile(join(postsDir, filename), 'utf8');
    return parsePost(source, filename);
  }),
);

const output = `// Generated by scripts/generate-agent-writing.mjs. Do not edit directly.
export const WRITING_POSTS = ${JSON.stringify(posts, null, 2)};
`;

const current = await readFile(outputUrl, 'utf8').catch(() => '');
if (current !== output) {
  await writeFile(outputUrl, output, 'utf8');
  console.log(`Updated ${fileURLToPath(outputUrl)}`);
}
